interface PreferencesContextValue {
  language: AppLanguage;
  theme: AppTheme;
  setLanguage: (language: AppLanguage) => void;
  toggleTheme: () => void;
  t: (text: string) => string;
}

const PreferencesContext = createContext<PreferencesContextValue | null>(null);

function storedLanguage(): AppLanguage {
  const value = localStorage.getItem('cotiz_language');
  return appLanguages.some(language => language.code === value) ? value as AppLanguage : 'fr';
}

function storedTheme(): AppTheme {
  return localStorage.getItem('cotiz_theme') === 'dark' ? 'dark' : 'light';
}

export const PreferencesProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [language, setLanguage] = useState<AppLanguage>(storedLanguage);
  const [theme, setTheme] = useState<AppTheme>(storedTheme);

  useEffect(() => {
    localStorage.setItem('cotiz_language', language);
    document.documentElement.lang = language;
  }, [language]);

  useEffect(() => {
    localStorage.setItem('cotiz_theme', theme);
    document.documentElement.classList.toggle('dark', theme === 'dark');
    document.documentElement.style.colorScheme = theme;
  }, [theme]);

  const value = useMemo<PreferencesContextValue>(() => ({
    language,
    theme,
    setLanguage,
    toggleTheme: () => setTheme(current => current === 'light' ? 'dark' : 'light'),
    t: (text: string) => frequencyTranslations[language][text]
      ?? (language === 'fr' ? text : translations[language][text] ?? screenTranslations[language][text] ?? text),
  }), [language, theme]);

  return <PreferencesContext.Provider value={value}>{children}</PreferencesContext.Provider>;
};

export function usePreferences(): PreferencesContextValue {
  const context = useContext(PreferencesContext);
  if (!context) throw new Error('usePreferences must be used within a PreferencesProvider');
  return context;
}
